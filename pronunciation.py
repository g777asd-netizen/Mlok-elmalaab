def _int_to_egy(n):
    if n in _NUM_WORDS:
        return _NUM_WORDS[n]
    if n < 100:
        t, u = divmod(n, 10)
        return f"{_NUM_WORDS[u]} و{_NUM_WORDS[t*10]}"
    if n < 1000:
        h, r = divmod(n, 100)
        hw = {1: "مية", 2: "ميتين", 3: "تلتمية", 4: "ربعمية", 5: "خمسمية", 6: "ستمية",
              7: "سبعمية", 8: "تمنمية", 9: "تسعمية"}[h]
        return hw if r == 0 else f"{hw} و{_int_to_egy(r)}"
    if n < 100000:
        k, r = divmod(n, 1000)
        kw = {1: "ألف", 2: "ألفين"}.get(k) or (f"{_int_to_egy(k)} آلاف" if k <= 10 else f"{_int_to_egy(k)} ألف")
        return kw if r == 0 else f"{kw} و{_int_to_egy(r)}"
    return str(n)


_NUMW = "(?:" + "|".join(sorted({v for v in _NUM_WORDS.values()}, key=len, reverse=True)) + ")"
_STRAY = r"(?:لايف|لَايف|لايڤ|live|Live)"

def fix_score_words(text):
    """'أربعة لايف صفر' -> 'أربعة صفر' (كلمة لايف الغريبة بين رقمين)."""
    return re.sub("(" + _NUMW + ")\\s+" + _STRAY + "\\s+(" + _NUMW + ")", lambda m: m[1] + " " + m[2], text)


def numbers_to_words(text):
    """نتيجة 4-0 -> أربعة صفر. باقي الأرقام -> كلمات مصرية."""
    t = text.translate(str.maketrans(AR_DIGITS, "0123456789"))
    t = re.sub(r"(\d+)\s*(?:[-:–]|\s(?:لايف|live|Live)\s)\s*(\d+)", lambda m: f"{_int_to_egy(int(m[1]))} {_int_to_egy(int(m[2]))}", t)
    t = re.sub(r"(\d+)", lambda m: _int_to_egy(int(m[1])), t)
    return fix_score_words(t)


def _norm_key(s):
    return re.sub("[\u064B-\u0652\u0640]", "", s)


AR_LET = "\u0621-\u064A"


def _whole(word):
    return "(?<![" + AR_LET + "])" + re.escape(word) + "(?![" + AR_LET + "])"


def respell_names(text):
    """استبدال كلمات كاملة فقط، الأطول أولاً (يمنع تخريب كلمات تانية)."""
    for src, dst in sorted(NAMES.items(), key=lambda kv: -len(kv[0])):
        text = re.sub(_whole(src), lambda m, d=dst: d, text)
    return text


def egyptianize(text):
    """تبديل آمن لكلمات فصحى شائعة بمرادف مصري (كلمات كاملة، الأطول أولاً)"""
    for src, dst in sorted(EGY_TERMS.items(), key=lambda kv: -len(kv[0])):
        text = re.sub(_whole(src), lambda m, d=dst: d, text)
    return re.sub(r"\s+", " ", text).strip()


def dialect_leftovers(script):
    """بقايا فصحى/غير مصرية في السكريبت (مرة واحدة لكل كلمة)"""
    found = []
    for w in DIALECT_FLAGS:
        if re.search(_whole(w) if " " not in w else re.escape(w), script):
            found.append(w)
    return found


def strip_bad_phrases(text):
    for bad, good in BAD_PHRASES.items():
        text = re.sub(_whole(bad), lambda m, g=good: g, text)
    return re.sub(r"\s+", " ", text).strip()


def prepare_for_speech(text):
    """يتنده قبل TTS: عبارات غلط، أرقام->كلمات، قاموس النطق."""
    text = strip_bad_phrases(text)
    text = egyptianize(text)
    text = numbers_to_words(text)
    return respell_names(text)


def script_problems(script, source_text, check_names=False):
    """قائمة مشاكل. لو مش فاضية: أعد التوليد (موديل تاني) بدل النشر."""
    probs = []
    if re.search(r"\d", script):
        probs.append("فيه أرقام لازم تتكتب بالكلمات")
    if re.search("(?<![" + AR_LET + "])" + _STRAY + "(?![" + AR_LET + "])", script) or re.search(r"[A-Za-z]{2,}", script):
        probs.append("كلمة غريبة (لايف/إنجليزي) في السكريبت")
    for bad in BAD_PHRASES:
        if bad and re.search(_whole(bad), script):
            probs.append("تعبير غلط: " + bad)
    left = dialect_leftovers(script)
    if len(left) >= 3:
        probs.append("لهجة مش مصرية كفاية، بقايا: " + "، ".join(left[:6]))
    if re.search(r"(\S+)\s+\1\s+\1", script):
        probs.append("تكرار كلمة ثلاث مرات ورا بعض")
    if check_names:
        for sent, nm in suspicious_name_sentences(script, source_text):
            probs.append("اسم مش في المصدر: " + nm)
    return probs


# كلمات عادية بتيجي بعد (اللاعب/المدرب) وملهاش علاقة باسم شخص
COMMON_NOT_NAMES = set("""رئيسي سنة سنه موسم الموسم هذا هذه ده دي اللي الذي التي كان كانت كل بعد قبل مع في من على الى إلى عن
أول اول تاني ثاني ثالث جديد جديدة كبير كبيرة صغير الشاب الكبير الجديد الاول الأول الأفضل الافضل الوحيد الاساسي الأساسي
يوم امبارح انهارده النهاردة دايما دايماً بس لسه لسة قدام ورا عشان علشان لكن ولا وكمان كمان برضه برضو
الفريق الفرقة الدوري الماتش المباراة المباريات الجون الهدف النادي الاتحاد الاتحادية الكرة الملعب
يقدم قدم يلعب لعب سجل يسجل جاب يجيب بيلعب بيقدم هيلعب هيقدم مش ما لا""".split())

TITLE_WORDS = ("المدرب", "اللاعب", "مدرب", "لاعب")


def suspicious_name_sentences(script, source_text):
    """جمل فيها (لاعب/مدرب + اسمين) والاسمين الاتنين مش في المصدر ومش كلمات عادية.
    فلتر متساهل: بيتجاهل الكلمات الشائعة وبيكتفي بتحذير لما الاسمين كلهم مش موجودين في الخبر."""
    src = _norm_key(source_text)
    pat = "(?:" + "|".join(TITLE_WORDS) + ")\\s+([" + AR_LET + "]{3,})\\s+([" + AR_LET + "]{3,})"
    out = []
    for sent in re.split(r"(?<=[\.!\?؟])\s+", script):
        for m in re.finditer(pat, sent):
            w1, w2 = _norm_key(m[1]), _norm_key(m[2])
            if w1 in COMMON_NOT_NAMES or w2 in COMMON_NOT_NAMES:
                continue
            if w1 in src or w2 in src:
                continue
            out.append((sent, m[1] + " " + m[2]))
    return out


def drop_suspicious_sentences(script, source_text):
    """بدل ما نرفض السكريبت: نشيل الجملة المشبوهة بس (لو فضل نص كفاية)."""
    bad = {s for s, _ in suspicious_name_sentences(script, source_text)}
    if not bad:
        return script, []
    sents = re.split(r"(?<=[\.!\?؟])\s+", script)
    kept = [s for s in sents if s not in bad]
    if len(" ".join(kept)) < 0.6 * len(script):
        return script, []
    return " ".join(kept), list(bad)
